"""Demo 0.1 dynamic flash drum: ethanol/water fed to a heated drum at atmospheric pressure.

Authored with the shared fundamental-law tools (tests/derived_closure_inputs.author_drum): component mass and
energy conservation with a feed at a declared exterior state, a vapour vent and a liquid orifice that draw the
package phases (UNIFAC Dortmund), a heat duty, and the level from the liquid volume of the package closure.

The drum starts as 100 kg of subcooled liquid (20 % ethanol by mass, 300 K). The feed (0.5 kg/s, 10 mol %
ethanol, 330 K) and the 200 kW duty heat it to its bubble point, where the vapour appears as a located phase
event; it then settles to a two-phase steady state with a rising level. The orifice (3 cm2) and vent coefficient
are demonstration values.

    python tests/demo01_flash.py --write     regenerates frontend/testing/demo01/flashDrum.ts
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'tests'))

from derived_closure_inputs import DRUM, author_drum, select_drum  # noqa: E402

FIXTURE = ROOT / 'frontend' / 'testing' / 'demo01' / 'flashDrum.ts'
HEADER = ('/** Generated by tests/demo01_flash.py --write from the shared Python authoring; do not edit by hand.\n'
          ' * Internal regression fixture (Demo 0.1), never a product-library template. */\n')
DEMO = dict(DRUM, orifice=3e-4, tf=3000.0)


def author_demo_flash():
    author, out = author_drum(DEMO)
    model = select_drum(author, out, DEMO)
    model.update(id='demo-0.1-flash-drum', nombre='Demo 0.1 · Heated ethanol-water flash drum')
    return model


def publication(model):
    return HEADER + 'export const DEMO01_FLASH_DRUM = ' + json.dumps(model, indent=1, ensure_ascii=False, sort_keys=True) + ';\n'


def frozen_model():
    text = FIXTURE.read_text(encoding='utf-8')
    return json.loads(text[text.index(' = ') + 3:text.rindex(';')])


if __name__ == '__main__':
    text = publication(author_demo_flash())
    if '--write' in sys.argv:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(text, encoding='utf-8', newline='\n')
        print('wrote', FIXTURE.relative_to(ROOT))
    else:
        sys.stdout.buffer.write(text.encode('utf-8'))   # UTF-8 and LF on every platform, byte-equal to --write
