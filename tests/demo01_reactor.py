"""Demo 0.1 batch reactor: liquid-phase esterification of ethanol with acetic acid in a jacketed vessel.

Authored with the shared fundamental-law tools (tests/derived_reactor_inputs.author_reactor): component mass
conservation with forward and reverse power-law kinetics, the first law with a jacket and the package caloric
inventory (UNIFAC Dortmund, liquid-only acetic acid, liquid formation reference, tabulated acetic acid cp_L).

The rates are in detailed balance with the package equilibrium at the jacket temperature:
    kr(Tref) = kf(Tref) / K_x,eq(Tref)         K_x,eq = n_EtOAc n_H2O / (n_EtOH n_AcOH) at the certified
                                               Gibbs minimum (Delta nu = 0, so K_c = K_x)
    Er = Ef - Delta_r H(Tref)                  van 't Hoff, so K_c(T) follows K(T) to first order
Ef = 50 kJ/mol and kf(340 K) = 1e-7 m3/(mol s) are demonstration values (time constant about 10 min), not
fitted kinetics. The vessel starts at 320 K and the jacket (UA 5 W/K) holds 340 K.

Scope (review RD-1, RD-2 and RD-5, 31 October 2026):
- kr and Er enter the model as data computed here. The common model has no per-datum provenance, and no shared
  operation yet derives a reverse rate from the package equilibrium (a pending Engine capability). So editing kf,
  Ef, Tref, the charge or the package does not update them. The Results row reactions.equilibrium_limit then
  reports the mismatch, and tests/test_demo01_reactor.py recomputes both values from the fixture's own data.
- With UNIFAC, K_x depends on composition. Concentration power-law rates therefore end at the Gibbs minimum only
  on this charge's reaction line, and only to first order in T away from Tref. A 2:1 ethanol charge gives
  Gibbs K_x(340 K) = 3.417 against the kinetic 3.671. Activity-based rates are a later extension.
- The rates use the 0.65 L vessel volume, while the charged liquid occupies n v_L = 0.58 L. This is a data
  choice inherited from the reactor test. The system range is 289.81-391.05 K, bounded by the acetic acid cp_L
  correlation.

    python tests/demo01_reactor.py --write     regenerates frontend/testing/demo01/batchReactor.ts
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'tests'))

from derived_reactor_inputs import REACTOR, SPECIES, ELEMENTS, author_reactor  # noqa: E402
from derived_closure_inputs import PACKAGE_ID  # noqa: E402

FIXTURE = ROOT / 'frontend' / 'testing' / 'demo01' / 'batchReactor.ts'
HEADER = ('/** Generated by tests/demo01_reactor.py --write from the shared Python authoring; do not edit by hand.\n'
          ' * Internal regression fixture (Demo 0.1), never a product-library template. */\n')
DEMO = dict(REACTOR, T0=320.0, Tj=340.0, UA=5.0, Tref=340.0, kf=1e-7, E=5.0e4, tf=10800.0)


def detailed_balance(data=DEMO):
    """kr and Er from the package: certified equilibrium composition and reaction enthalpy at Tref."""
    from core import mezclas
    from core.reactions import chemical_equilibrium as ce
    from core.termodinamica import derived_bridge
    phase = ce.PackagePhase(mezclas.Sistema(PACKAGE_ID, list(SPECIES), solo_liquido=True), 'liquido', anchor='liquid')
    A = np.array([ELEMENTS[e] for e in ('C', 'H', 'O')], dtype=float)
    nu = [[-1, -1, 1, 1]]
    n = np.array(ce.minimise_gibbs(phase, nu, np.array(data['n0']), data['Tref'], data['P'], A)['moles'])
    K = n[2] * n[3] / (n[0] * n[1])
    dH = derived_bridge.reaction_enthalpy(PACKAGE_ID, list(SPECIES), nu, data['Tref'], data['P'], n=n,
                                          anchor='liquid', liquid_only=True)['dH'][0]
    return {'K': float(K), 'dH': float(dH), 'kr': data['kf'] / float(K), 'Er': data['E'] - float(dH), 'equilibrium': n.tolist()}


def demo_data():
    balance = detailed_balance()
    return dict(DEMO, kr=balance['kr'], Er=balance['Er'])


def author_demo_reactor():
    model = author_reactor(demo_data())
    model.update(id='demo-0.1-batch-reactor', nombre='Demo 0.1 · Jacketed esterification batch reactor')
    return model


def publication(model):
    return HEADER + 'export const DEMO01_BATCH_REACTOR = ' + json.dumps(model, indent=1, ensure_ascii=False, sort_keys=True) + ';\n'


def frozen_model():
    text = FIXTURE.read_text(encoding='utf-8')
    return json.loads(text[text.index(' = ') + 3:text.rindex(';')])


if __name__ == '__main__':
    text = publication(author_demo_reactor())
    if '--write' in sys.argv:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(text, encoding='utf-8', newline='\n')
        print('wrote', FIXTURE.relative_to(ROOT))
    else:
        sys.stdout.buffer.write(text.encode('utf-8'))   # UTF-8 and LF on every platform, byte-equal to --write
