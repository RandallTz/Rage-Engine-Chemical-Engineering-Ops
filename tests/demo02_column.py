"""Demo 0.2 equipment template: a dynamic countercurrent equilibrium-stage cascade.

One generic stage j is authored with the shared fundamental-law tools: component
mass, the first law and momentum, exactly as the flash drum
(tests/demo02_drum.py) through tests/derived_momentum_inputs.author_outlet. The
stage has three material inlets at declared exterior states (an external feed,
the liquid arriving from the stage above and the vapour arriving from the stage
below), a vapour withdrawal drawn from the vapour phase, a liquid outlet whose
flow is the momentum state of a straight downcomer path (liquid head against a
local loss), a heat duty, and the UNIFAC (Dortmund) package closure of
benzene-toluene with the always-present phase equilibrium (the ideal package has
no derived-execution closure adapter yet; see the column report). Each extra inlet is
substituted into the same recorded component and energy balances with the same
recorded operations as the feed; no stage-specific balance is written.

The column is a rage.index-set v1 network of that one stage: liquid outlet of j
to the liquid inlet of j+1 (offset +1), vapour outlet of j to the vapour inlet
of j-1 (offset -1). The partial condenser (stage 1), the feed stage and the
reboiler (stage n) are variants of the same recorded stage that differ only in
their recorded boundary data: a negative heat duty, a nonzero external feed and
a positive heat duty. The unused end inlets (liquid into the condenser, vapour
into the reboiler) are exposed ports with a zero recorded inlet rate.

    python tests/demo02_column.py --write   regenerates frontend/testing/demo02/column.ts
"""
