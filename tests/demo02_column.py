def stage_source(data=DEMO):
    """One prescribed-pressure package stage with a feed, two internal inlets and two phase outlets."""
    model = thermal_source((OWNER,))
    model.update(id='demo-0.2-column-stage', nombre='Demo 0.2 · Equilibrium stage')
    model['componentes'] = [{'id': 1, 'nombre': 'benzene', 'simbolo': 'C6H6', 'identidadQuimica': {'cas': BENZENE}},
                            {'id': 2, 'nombre': 'toluene', 'simbolo': 'C7H8', 'identidadQuimica': {'cas': TOLUENE}}]
    volume = model['volumenes'][0]
    volume['componenteIds'] = [1, 2]
    model['datos'][OWNER + '.mass2'] = copy.deepcopy(model['datos'][OWNER + '.mass'])
    volume['inicial']['cantidades']['datoIds']['2'] = OWNER + '.mass2'
    model['datos'][OWNER + '.mass']['declaracion']['texto'] = repr(data['m0'][0])
    model['datos'][OWNER + '.mass2']['declaracion']['texto'] = repr(data['m0'][1])
    model['datos'][OWNER + '.temperature']['declaracion']['texto'] = repr(data['T0'])
    model['termodinamica'] = {'paquetes': [{'id': 'pkg', 'modelo': {'id': PACKAGE_ID, 'version': '1'}}]}
    volume['termodinamica'] = {'tipo': 'equilibrio', 'paqueteId': 'pkg', 'politica':
                               {'cantidad': 'sin_restriccion', 'cambioInterno': 'permitido', 'evaluacion': 'equilibrio_estable'}}
    journal = {'format': 'rage.material-derivation', 'version': 1, 'volumes': {}}
    for action in ('start', 'no_reaction', 'integrate', 'total', 'impermeable_remainder'):
        journal = material.edit_journal(journal, OWNER, {'kind': action})
    model['motores']['materialDerivation'] = journal
    volume['supuestos']['materia'] = material.replay_volume(journal['volumes'][OWNER])[-1]
    ej = {'format': 'rage.energy-derivation', 'version': 1, 'volumes': {}}
    for action in ('start', 'pressure_stress', 'no_kinetic', 'no_viscous_work', 'no_body_work', 'no_volume_source',
                   'integrate', 'reynolds', 'total', 'enthalpy', 'uniform_state', 'uniform_pressure', 'prescribed_pressure'):
        ej = energy.edit_journal(ej, OWNER, {'kind': action})
    model['motores']['energyDerivation'] = ej
    tj = {'format': thermodynamics.FORMAT, 'version': 1, 'volumes': {}}
    tj = thermodynamics.edit_journal(tj, OWNER, {'kind': 'start'})
    tj = thermodynamics.edit_journal(tj, OWNER, {'kind': 'select_closure'}, thermodynamics.expected_closure(model, volume))
    model['motores']['thermodynamicDerivation'] = tj
    es = replay(ej['volumes'][OWNER], energy.fundamental, energy.normalize)[-1]
    ts = replay(tj['volumes'][OWNER], thermodynamics.fundamental, thermodynamics.normalize)[-1]
    volume['supuestos']['energia'] = {**es, **{k: v for k, v in ts.items() if k != 'closure'}}
    _datum(model, OWNER + '.pressure', data['P'], 'Pa', 'frontera')
    volume['frontera'] = {'tipo': 'presion_prescrita', 'presionId': OWNER + '.pressure'}
    exterior = {'feed': dict(T=data['TF'], P=data['PF'], z=data['zF']), **{k: data[k] for k in INLETS}}
    model['corrientes'] = []
    for name in ('feed', *INLETS, 'liquid', 'vapour'):
        stream = {'id': name, 'desde': OWNER if name in ('liquid', 'vapour') else None,
                  'hasta': None if name in ('liquid', 'vapour') else OWNER,
                  'componenteIds': [1, 2], 'mecanismo': 'convectivo', 'constante': False,
                  'materia': {'modo': 'por_componente', 'base': 'masica', 'caudalIds': {}}}
        if name in exterior:
            state = exterior[name]
            _datum(model, name + '.T', state['T'], 'K', 'frontera')
            _datum(model, name + '.P', state['P'], 'Pa', 'frontera')
            stream['estadoExterior'] = {'temperaturaId': name + '.T', 'presion': {'tipo': 'dato', 'datoId': name + '.P'},
                                        'composicion': {'base': 'molar', 'fracciones': {'1': state['z'][0], '2': state['z'][1]}}}
        model['corrientes'].append(stream)
    return leer_modelo_comun(model)


def prepare(model, data=DEMO):
    """Boundary metadata read by the ports: phase extraction of the drawn streams and the heat term."""
    for stream in model['corrientes']:
        if stream['id'] == 'vapour':
            stream['extraccion'] = {OWNER: {'tipo': 'fase', 'fase': 'vapor'}}
        if stream['id'] == 'liquid':
            stream['extraccion'] = {OWNER: {'tipo': 'fase', 'fase': 'liquido'}}
    path = next(v for v in model['volumenes'] if v['id'] == PIPE)
    path['termodinamica']['motivo'] = 'The downcomer transports the drawn liquid phase without separate storage or a separate thermodynamic closure.'
    next(s for s in model['corrientes'] if s['id'] == 'discharge')['extraccion'] = {PIPE: {'tipo': 'fase', 'fase': 'liquido'}}


def template():
    inlet = lambda port, stream: {'id': port, 'volumeId': OWNER, 'direction': 'inlet', 'kind': 'material',
                                  'boundary': {'type': 'stream', 'id': stream}, 'exteriorState': 'estadoExterior',
                                  'variables': copy.deepcopy(MATERIAL)}
    return {'format': 'rage.model-template', 'version': 1, 'id': 'demo-02-column-stage', 'templateVersion': '1', 'equipment': True,
            'recipe': {'journals': ['materialDerivation', 'energyDerivation', 'momentumDerivation', 'thermodynamicDerivation', 'equationWorkbench']},
            'ports': [inlet('feed', 'feed'), inlet('liquidIn', 'liquidIn'), inlet('vapourIn', 'vapourIn'),
                      {'id': 'vapour', 'volumeId': OWNER, 'direction': 'outlet', 'kind': 'material', 'boundary': {'type': 'stream', 'id': 'vapour'},
                       'donorPhase': 'vapor', 'variables': copy.deepcopy(MATERIAL)},
                      {'id': 'liquid', 'volumeId': PIPE, 'direction': 'outlet', 'kind': 'material', 'boundary': {'type': 'stream', 'id': 'discharge'},
                       'donorPhase': 'liquido', 'variables': copy.deepcopy(MATERIAL)},
                      {'id': 'heat', 'volumeId': OWNER, 'direction': 'inlet', 'kind': 'heat', 'boundary': {'type': 'term', 'id': 'calor'},
                       'variables': {'power': {'unitSI': 'W'}}}]}


def heat_term(model, data):
    _datum(model, 'solve.Q', data['Q'], 'W')
    model['volumenes'][0]['terminos'] = {'calor': 'solve.Q'}


def author_stage(data=DEMO, method='bdf'):
    """The drum recipe plus the two internal inlets, substituted by the same recorded operations as the feed."""
    def prepared(model):
        prepare(model, data)
        heat_term(model, data)
    author, out = author_outlet(data, prepare=prepared, source_factory=stage_source, owner=OWNER)
    add, q = author.append, author.quantity
    f = lambda name: sp.Function(name)(T)
    o = OWNER
    for stream in INLETS:
        add('declare_symbol', name=RATES[stream], unit='kg/s')
    for i in (1, 2):
        current = out[f'mass.{i}']
        for stream in INLETS:
            inflow = author.relation(q(f(f'q__{stream}__{i}')), f"{RATES[stream]}*{q(f(f'inlet_mass_fraction_{i}__{stream}'))}",
                'Prescribed inlet rate with the package composition of the declared inlet state', kind='constitutive')
            out[f'{stream}.{i}'] = inflow
            current = author.substitute(current, inflow, f(f'q__{stream}__{i}'))
        out[f'mass.{i}'] = current
    current = out['energy']
    for stream in INLETS:
        for i in (1, 2):
            current = author.substitute(current, out[f'{stream}.{i}'], f(f'q__{stream}__{i}'), 'energy')
        average = f('energy_average_0__' + stream)
        relation = author.relation(q(average), q(f('inlet_specific_enthalpy__' + stream)),
            'Stream specific enthalpy from the package at the declared inlet state', 'energy', 'constitutive')
        out['enthalpy.' + stream] = relation
        current = author.substitute(current, relation, average, 'energy')
    out['energy'] = current
    author.model['template'] = template()
    model = select_outlet(author, out, data, method, owner=OWNER)
    replayed = build(model)
    quantities = {**catalog(replayed.graph, replayed.units), **replayed.introduced}
    selection = model['motores']['derivedExecution']
    for stream in INLETS:
        qid = next(k for k, v in quantities.items() if v == replayed.introduced[RATES[stream]])
        selection['parameters'][qid] = _datum(model, 'solve.' + RATES[stream], data[stream]['rate'], 'kg/s')
    model.update(id='demo-0.2-column-stage', nombre='Demo 0.2 · Equilibrium stage with downcomer momentum (equipment)')
    selection['sourceSignature'] = source_signature(model, replayed)
    return model, out


def variant(generic, name, *, heat=None, feed=None, loss=None, m0=(None, None)):
    """The same recorded stage with other recorded data (heat duty, feed rate, outlet loss, initial holdup)."""
    model = copy.deepcopy(generic)
    for key, value in [('solve.Q', heat), ('solve.F', feed), ('solve.K', loss),
                       (OWNER + '.mass', m0[0]), (OWNER + '.mass2', m0[1])]:
        if value is not None:
            model['datos'][key]['declaracion']['texto'] = repr(float(value))
    model.update(id='demo-0.2-column-' + name, nombre='Demo 0.2 · Equilibrium stage (' + name + ')')
    return model


def column_model(generic, count, feed_stage=None, *, condenser=CONDENSER_Q, reboiler=REBOILER_Q, feed=FEED['feed']):
    """rage.index-set v1 countercurrent cascade of the one recorded stage.

    Liquid descends (outlet j -> liquid inlet j+1), vapour ascends (outlet j -> vapour inlet j-1).
    Stage 1 is the partial condenser, stage n the reboiler, feed_stage receives the external feed.
    """
    if count < 3:
        raise ValueError('A condenser, at least one stage and a reboiler are required.')
    feed_stage = feed_stage or (count + 1) // 2
    model = copy.deepcopy(generic)
    model.update(id='demo-0.2-column', nombre='Demo 0.2 · Dynamic countercurrent equilibrium-stage column')
    _datum(model, 'solve.stageCount', count, '1', 'estudio')
    templates = {'generic': copy.deepcopy(generic), 'condenser': variant(generic, 'condenser', heat=condenser),
                 'reboiler': variant(generic, 'reboiler', heat=reboiler, **REBOILER), 'feed': variant(generic, 'feed', feed=feed)}
    model['indexSet'] = {'format': 'rage.index-set', 'version': 1, 'id': 'column', 'index': 'j',
        'countDataId': 'solve.stageCount', 'templates': templates, 'genericStage': 'generic',
        'variants': [{'at': 'first', 'template': 'condenser'}, {'at': 'last', 'template': 'reboiler'},
                     {'at': feed_stage, 'template': 'feed'}],
        'connections': [{'outlet': 'liquid', 'inlet': 'liquidIn', 'offset': 1},
                        {'outlet': 'vapour', 'inlet': 'vapourIn', 'offset': -1}],
        'exposures': [{'id': 'feed', 'port': 'feed', 'at': 'each'}, {'id': 'heat', 'port': 'heat', 'at': 'each'},
                      {'id': 'reflux', 'port': 'liquidIn', 'at': 'first'}, {'id': 'boilup', 'port': 'vapourIn', 'at': 'last'},
                      {'id': 'distillate', 'port': 'vapour', 'at': 'first'}, {'id': 'bottoms', 'port': 'liquid', 'at': 'last'}]}
    return model


def publication(model):
    return HEADER + 'export const DEMO02_COLUMN_STAGE = ' + json.dumps(model, indent=1, ensure_ascii=False, sort_keys=True) + ';\n'


def frozen_model():
    text = FIXTURE.read_text(encoding='utf-8')
    return json.loads(text[text.index(' = ') + 3:text.rindex(';')])


