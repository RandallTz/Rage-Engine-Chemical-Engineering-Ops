"""Demo 0.2 equipment template: heated flash drum deduced with matter, energy and momentum.

Authored with the shared fundamental-law tools (tests/derived_momentum_inputs.author_outlet): component mass,
the first law and momentum, with a feed at a declared exterior state, a vapour withdrawal drawn from the
vapour phase, a liquid outlet whose flow is the momentum state of a straight outlet path (driven by the
vapour-space pressure plus the liquid head, against the journal's Darcy-Weisbach/local-loss closure), a heat
duty, and the level from the liquid volume of the package closure (UNIFAC Dortmund). Every assumption is
phrased as physics. The model carries the equipment template record (rage.model-template v1) with typed,
unconnected ports for the feed, the vapour, the liquid and the heat boundaries.

    python tests/demo02_drum.py --write     regenerates frontend/testing/demo02/flashDrum.ts
"""
import json
import math
import sys
from pathlib import Path

import sympy as sp

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / 'tests'))

from derived_closure_inputs import OWNER, T, _datum  # noqa: E402
from derived_momentum_inputs import OUTLET, PIPE, author_outlet, select_outlet  # noqa: E402

FIXTURE = ROOT / 'frontend' / 'testing' / 'demo02' / 'flashDrum.ts'
HEADER = ('/** Generated by tests/demo02_drum.py --write from the shared Python authoring; do not edit by hand.\n'
          ' * Internal regression fixture (Demo 0.2 equipment template), never a product-library template. */\n')
DEMO = dict(OUTLET, tf=1200.0)
MATERIAL = {'flow': {'unitSI': 'kg/s'}, 'composition': {'unitSI': '1'}, 'temperature': {'unitSI': 'K'},
            'pressure': {'unitSI': 'Pa'}, 'specificEnthalpy': {'unitSI': 'J/kg'}}


def prepare(model, data=DEMO):
    """Boundary metadata read by the ports: phase extraction of the drawn streams and the heat term."""
    for stream in model['corrientes']:
        if stream['id'] == 'vapour':
            stream['extraccion'] = {OWNER: {'tipo': 'fase', 'fase': 'vapor'}}
        if stream['id'] == 'liquid':
            stream['extraccion'] = {OWNER: {'tipo': 'fase', 'fase': 'liquido'}}
    _datum(model, 'solve.Q', data['Q'], 'W')
    model['volumenes'][0]['terminos'] = {'calor': 'solve.Q'}


def template():
    return {'format': 'rage.model-template', 'version': 1, 'id': 'demo-02-drum', 'templateVersion': '2', 'equipment': True,
            'recipe': {'journals': ['materialDerivation', 'energyDerivation', 'momentumDerivation', 'thermodynamicDerivation', 'equationWorkbench']},
            'ports': [
                {'id': 'feed', 'volumeId': OWNER, 'direction': 'inlet', 'kind': 'material', 'boundary': {'type': 'stream', 'id': 'feed'},
                 'exteriorState': 'estadoExterior', 'variables': MATERIAL},
                {'id': 'vapour', 'volumeId': OWNER, 'direction': 'outlet', 'kind': 'material', 'boundary': {'type': 'stream', 'id': 'vapour'},
                 'donorPhase': 'vapor', 'variables': MATERIAL},
                {'id': 'liquid', 'volumeId': PIPE, 'direction': 'outlet', 'kind': 'material', 'boundary': {'type': 'stream', 'id': 'discharge'},
                 'donorPhase': None, 'variables': MATERIAL},
                {'id': 'heat', 'volumeId': OWNER, 'direction': 'inlet', 'kind': 'heat', 'boundary': {'type': 'term', 'id': 'calor'},
                 'variables': {'power': {'unitSI': 'W'}}}]}


def author_demo_drum(data=DEMO, method='rk45'):
    author, out = author_outlet(data, prepare=lambda model: prepare(model, data))
    author.model['template'] = template()
    model = select_outlet(author, out, data, method)
    # Publish the liquid level: the free-surface elevation above the floor (floor at 0 m).
    from core.modelo.equation_workbench import build
    from core.mathematics.dimensions import catalog
    replayed = build(model)
    quantities = {**catalog(replayed.graph, replayed.units), **replayed.introduced}
    surface = replayed.graph.nodes[out['surface']].equation.lhs
    model['motores']['derivedExecution']['reconstructions'].append(
        {'quantityId': next(k for k, v in quantities.items() if v == surface), 'equationId': out['surface']})
    model.update(id='demo-0.2-flash-drum', nombre='Demo 0.2 · Heated flash drum with outlet momentum (equipment)')
    return model, out


def publication(model):
    return HEADER + 'export const DEMO02_FLASH_DRUM = ' + json.dumps(model, indent=1, ensure_ascii=False, sort_keys=True) + ';\n'


def frozen_model():
    text = FIXTURE.read_text(encoding='utf-8')
    return json.loads(text[text.index(' = ') + 3:text.rindex(';')])


if __name__ == '__main__':
    text = publication(author_demo_drum()[0])
    if '--write' in sys.argv:
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(text, encoding='utf-8', newline='\n')
        print('wrote', FIXTURE.relative_to(ROOT))
    else:
        sys.stdout.buffer.write(text.encode('utf-8'))
