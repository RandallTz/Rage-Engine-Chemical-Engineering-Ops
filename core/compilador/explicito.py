"""
Common-model compiler: explicit equations.

The compiler's second entry point, alongside the structural one (compilador.py).
Execute `modelo.matematico` equations (the typed v2 document tree) as written,
without knowing which equipment, operation or substance they describe:

    d u_k / dt = f_k(t, u, parameters)     one equation per field variable
    u_k(0)     = g_k(parameters)           one initial condition per variable

Values: each parameter or constant takes its value from
`datos["matematico.<id>"]` in any unit compatible with the symbol's dimension;
the shared units service converts it to SI and checks compatibility.
The final time is the datum `estudio.tiempoId`.

Domain: `modelo.restricciones` (no_negativo) stops the trajectory at the
instant a variable would leave its domain, located by bisection. Values
are never clipped and execution never continues outside the domain.

Outside this entry point's scope (NoSoportado with a reason): spatial
derivatives and differential operators (handled by the discretization engine),
algebraic equations (DAEs), derivatives above first order, and declared
functions without definitions.
"""

import math

import numpy as np

from core import expresiones_motor as ex
from core import unidades as un
from core.modelo import leer_modelo_comun
from core.resultados import conjunto, eje, evento, serie
from core.solvers import integrar

from .compilador import AdmissionError, NoSoportado, temporal_method

PREFIJO = "matematico."
_FUNCIONES = {"exp": math.exp, "log": math.log, "sin": math.sin, "cos": math.cos, "tan": math.tan, "tanh": math.tanh,
              "sinh": math.sinh, "cosh": math.cosh, "atan": math.atan, "erf": math.erf, "abs": abs}
_NOMBRE_METODO = {"RK45": "Adaptive RK45 (Dormand-Prince 5/4, core/solvers)",
                  "BDF": "Implicit variable-order BDF (core/solvers)"}


def es_explicito(modelo):
    """A model without equilibrium-closure volumes: its equations are authored
    or generated by the balance engine from the volume assumptions."""
    return all(v["termodinamica"]["tipo"] == "supuesto" for v in modelo["volumenes"]) and (
        modelo.get("matematico") is not None or bool(modelo["volumenes"]))


def _dim_de_simbolo(s):
    d = s["dimension"]
    if d is None:
        raise NoSoportado(f"matematico: symbol {s['id']} has no declared dimension")
    fuera = sorted(set(d) - set(un.BASES.values()))
    if fuera:
        raise NoSoportado(f"matematico: symbol {s['id']} uses dimensions outside the SI bases ({', '.join(fuera)})")
    from fractions import Fraction
    return {k: Fraction(v["n"], v["d"]) for k, v in d.items() if v["n"]}


def _valor_SI(dato, ruta, dim):
    texto, unidad = dato["declaracion"]["texto"], dato["declaracion"]["unidad"]
    if not texto.strip():
        raise AdmissionError('missing_data', 'A numerical datum is pending.', ruta)
    try:
        i = un.interpretar(unidad)
    except un.ErrorUnidad as e:
        raise AdmissionError('incompatible_dimension', str(e), ruta) from e
    if i["dimension"] != dim:
        raise AdmissionError('incompatible_dimension', 'The datum unit does not match the symbol dimension: '+unidad, ruta)
    try:
        arbol = ex.analizar(texto, [])
        value = i["factor"] * ex.evaluar(arbol, {}) + i["desplazamiento"]
        if not math.isfinite(value):
            raise ValueError('The datum must evaluate to a finite SI value.')
        return value
    except (ValueError, ArithmeticError) as error:
        raise AdmissionError('invalid_data', str(error), ruta) from error


class SistemaExplicito:
    def __init__(self, modelo, *, _structure_only=False):
        from core.modelo.lector import leer_modelo_inspeccion
        self.modelo = (leer_modelo_inspeccion if _structure_only else leer_modelo_comun)(modelo)
        mat = self.modelo["matematico"]
        if mat is None:
            raise NoSoportado("The model has no explicit equations (matematico)")
        if mat["funciones"]:
            raise NoSoportado("Declared functions without definitions: " + ", ".join(f["id"] for f in mat["funciones"]))
        sim = {s["id"]: s for s in mat["simbolos"]}
        tiempos = [s["id"] for s in mat["simbolos"] if s["rol"] == "tiempo"]
        if len(tiempos) != 1:
            raise NoSoportado("matematico: exactly one time variable is required")
        self.tiempo = tiempos[0]
        if any(s["rol"] == "coordenada" for s in mat["simbolos"]):
            raise NoSoportado("Fields with spatial coordinates require the discretization engine (step 5.2)")
        self.campos = [s["id"] for s in mat["simbolos"] if s["rol"] == "campo"]
        if not self.campos:
            raise NoSoportado("matematico: no field variables to integrate")
        self.indice = {c: k for k, c in enumerate(self.campos)}
        self.dims = {c: _dim_de_simbolo(sim[c]) for c in self.campos}
        dim_t = _dim_de_simbolo(sim[self.tiempo])
        # Parameters and constants in SI, restricted to those used by the tree.
        usados = set()
        for e in mat["ecuaciones"]:
            _simbolos(e["izquierda"], usados)
            _simbolos(e["derecha"], usados)
        for c in ([] if _structure_only else mat["condiciones"]):
            _simbolos(c["ecuacion"]["izquierda"], usados)
            _simbolos(c["ecuacion"]["derecha"], usados)
        # A parameter used only by a reconstructed observable or a validity
        # condition is still a numerical input of this same explicit system.
        for item in self.modelo.get('observables', []):
            _simbolos(item['expresion'], usados)
        for item in self.modelo.get('restricciones', []):
            if 'expresion' in item:
                _simbolos(item['expresion'], usados)
        for item in self.modelo.get('verificaciones', []):
            _simbolos(item['expresion'], usados)
            _simbolos(item['escala'], usados)
        self.valores = {}
        for sid in sorted(usados):
            s = sim.get(sid)
            if s is None:
                raise NoSoportado(f"matematico: unknown symbol {sid!r}")
            if s["rol"] in ("parametro", "constante"):
                clave = PREFIJO + sid
                if clave not in self.modelo["datos"]:
                    raise AdmissionError('missing_data', 'Missing value for '+sid, 'datos.'+clave)
                self.valores[sid] = _valor_SI(self.modelo["datos"][clave], f"datos.{clave}", _dim_de_simbolo(s))
        # One first-order differential equation per field variable.
        self.f = [None] * len(self.campos)
        for e in mat["ecuaciones"]:
            lado, otro = (e["izquierda"], e["derecha"]) if e["izquierda"]["tipo"] == "derivada" else (e["derecha"], e["izquierda"])
            if lado["tipo"] != "derivada" or lado["expresion"]["tipo"] != "simbolo" or lado["respecto"] != self.tiempo:
                raise NoSoportado(f"Equation {e['id']}: this entry point only executes d(variable)/d{self.tiempo} = expression (algebraic equations and DAEs are unsupported here)")
            if lado["orden"] != 1:
                raise NoSoportado(f"Equation {e['id']}: derivative of order {lado['orden']}: rewrite as a first-order system")
            u = lado["expresion"]["id"]
            if u not in self.indice:
                raise NoSoportado(f"Equation {e['id']}: {u} is not a field variable")
            if self.f[self.indice[u]] is not None:
                raise AdmissionError('STRUCTURE_CONFLICT', 'More than one differential equation declares the rate of '+u, 'matematico.ecuaciones')
            self.f[self.indice[u]] = self._compilar(otro, f"Equation {e['id']}")
        faltan = [c for c, f in zip(self.campos, self.f) if f is None]
        if faltan:
            raise AdmissionError('STRUCTURE_MISSING_RELATION', 'Missing differential equations for: '+', '.join(faltan), 'matematico.ecuaciones')
        # Domain: nonnegative variables and expressions that must stay >= 0 (assumption validity).
        self.dominios = []
        for r in self.modelo.get("restricciones", []):
            if "simboloId" in r:
                k = self.indice[r["simboloId"]]
                self.dominios.append((lambda tt, y, k=k: y[k], r["simboloId"]))
            else:
                self.dominios.append((self._compilar(r["expresion"], "constraint"), r["descripcion"]))
        self.restringidas = [self.indice[r["simboloId"]] for r in self.modelo.get("restricciones", []) if "simboloId" in r]
        est = self.modelo["estudio"]
        if est is None or est["tipo"] != "temporal":
            raise NoSoportado("The model does not request a time-dependent study")
        if est.get("espacial") and any(self.modelo["volumenes"][k]["frontera"]["tipo"] == "malla_1d" for k in range(len(self.modelo["volumenes"]))):
            raise NoSoportado("A volume with a 1D mesh requires the discretization engine (step 5.2)")
        dt = self.modelo["datos"][est["tiempoId"]]
        self.tf = _valor_SI(dt, f"datos.{est['tiempoId']}", dim_t)
        if not (self.tf > 0 and math.isfinite(self.tf)):
            raise NoSoportado(f"datos.{est['tiempoId']}: the final time must be positive and finite")
        self.metodo = temporal_method(est["metodoSolicitado"])
        self.unidades = {c: un.unidad_SI(self.dims[c]) for c in self.campos}
        self.unidad_t = un.unidad_SI(dim_t)
        # Derived quantities published as series, and checks that must be ~0 at each sample.
        self.observables = [(o["id"], o["nombre"], o["unidadSI"], self._compilar(o["expresion"], f"observable {o['id']}"))
                            for o in self.modelo.get("observables", [])]
        self.verificaciones = [(v["id"], v["descripcion"], self._compilar(v["expresion"], f"Verification {v['id']}"),
                                self._compilar(v["escala"], f"Verification {v['id']}"), v.get("tolerancia", 1e-9))
                               for v in self.modelo.get("verificaciones", [])]
        ENERGIA = {"M": 1, "L": 2, "T": -2}
        a = self.modelo["estudio"]["atol"]
        self.atol = np.array([a.get("energia", a["cantidad"]) if {k: int(v) for k, v in self.dims[c].items()} == ENERGIA else a["cantidad"]
                              for c in self.campos])
        if _structure_only:
            # Inspection has no initial vector and is never sent to a solver.
            return
        self.g = [None] * len(self.campos)
        initial_constraints = [[] for _ in self.campos]
        for c in mat["condiciones"]:
            if c["tipo"] != "inicial":
                raise NoSoportado(f"Condition {c['id']}: {c['tipo']} requires spatial coordinates")
            iz, de = c["ecuacion"]["izquierda"], c["ecuacion"]["derecha"]
            if iz["tipo"] != "simbolo" or iz["id"] not in self.indice:
                raise NoSoportado(f"Condition {c['id']}: expected variable = expression")
            if _usa_campos(de, self.indice) or _usa(de, self.tiempo):
                raise NoSoportado(f"Condition {c['id']}: the initial value cannot depend on variables")
            function = self._compilar(de, f"Condition {c['id']}")
            index = self.indice[iz['id']]
            initial_constraints[index].append((c['id'], c['ecuacion']['id'], function))
            self.g[index] = function
        faltan = [c for c, g in zip(self.campos, self.g) if g is None]
        if faltan:
            raise AdmissionError('INITIALIZATION_MISSING_DATA', 'Missing initial conditions for: '+', '.join(faltan), 'matematico.condiciones')
        self._check_initial_constraints(initial_constraints)
        self.validate_initial_state()

    def validate_initial_state(self):
        """Compilation and execution share the same initial-domain contract."""
        try:
            initial = self.inicial()
            margins = self.dominio(0.0, initial)
            if not np.isfinite(initial).all() or not np.isfinite(margins).all() or (margins < 0).any():
                raise ValueError('The initial state violates its declared finite domain.')
        except (ArithmeticError, ValueError) as error:
            raise AdmissionError('INITIALIZATION_OUT_OF_DOMAIN', str(error), 'matematico.condiciones') from error

    # --- tree -> function ---------------------------------------------------------------
    def _compilar(self, e, donde):
        t = e["tipo"]
        if t == "numero":
            v = float(e["valor"])
            return lambda tt, y: v
        if t == "simbolo":
            sid = e["id"]
            if sid == self.tiempo:
                return lambda tt, y: tt
            if sid in self.indice:
                k = self.indice[sid]
                return lambda tt, y: y[k]
            v = self.valores[sid]
            return lambda tt, y: v
        if t in ("suma", "producto"):
            fs = [self._compilar(a, donde) for a in e["argumentos"]]
            if t == "suma":
                return lambda tt, y: math.fsum(f(tt, y) for f in fs)
            def prod(tt, y):
                p = 1.0
                for f in fs:
                    p *= f(tt, y)
                return p
            return prod
        if t == "cociente":
            a, b = self._compilar(e["numerador"], donde), self._compilar(e["denominador"], donde)
            return lambda tt, y: a(tt, y) / b(tt, y)
        if t == "potencia":
            a, b = self._compilar(e["base"], donde), self._compilar(e["exponente"], donde)
            def pot(tt, y):
                r = a(tt, y) ** b(tt, y)
                if isinstance(r, complex):
                    raise ValueError("Power outside its domain (negative base with a noninteger exponent)")
                return r
            return pot
        if t == "funcion":
            fs = [self._compilar(a, donde) for a in e["argumentos"]]
            n = e["nombre"]
            if n in ("min", "max"):
                g = min if n == "min" else max
                return lambda tt, y: g(f(tt, y) for f in fs)
            h = _FUNCIONES[n]
            return lambda tt, y: h(fs[0](tt, y))
        if t == "llamada":
            raise NoSoportado(f"{donde}: declared function {e['funcionId']} has no definition")
        if t == "derivada":
            raise NoSoportado(f"{donde}: derivative inside the right-hand side (with respect to {e['respecto']}): requires the discretization engine")
        raise NoSoportado(f"{donde}: operator {t}: requires the discretization engine (step 5.2)")

    def _check_initial_constraints(self, constraints):
        """Check every repeated constraint after SI binding, before execution.

        Exact equality of the evaluated SI values is deliberately conservative:
        integration tolerances cannot turn contradictory declarations into an
        accepted initial state. A single constraint keeps its existing path.
        """
        diagnostics = []
        for index, rows in enumerate(constraints):
            if len(rows) < 2:
                continue
            rows = sorted(rows, key=lambda row: row[0])
            common = {'stage': 'initialization', 'initializationStatus': 'incompatible',
                      'path': 'matematico.condiciones', 'variableId': self.campos[index],
                      'conditionIds': [row[0] for row in rows],
                      'equationIds': [row[1] for row in rows],
                      'unitSI': un.unidad_SI(self.dims[self.campos[index]])}
            try:
                values = [float(row[2](0.0, None)) for row in rows]
                if not all(math.isfinite(value) for value in values):
                    raise ValueError('Initial constraints must evaluate to finite SI values.')
            except (ArithmeticError, ValueError) as error:
                diagnostics.append({**common, 'code': 'INITIALIZATION_OUT_OF_DOMAIN',
                                    'message': 'Cannot evaluate the initial constraints: '+str(error)})
                continue
            if any(value != values[0] for value in values[1:]):
                diagnostics.append({**common, 'code': 'INITIALIZATION_CONSTRAINT_CONFLICT',
                    'message': 'Conflicting initial constraints for '+self.campos[index]+': '+', '.join(common['conditionIds']),
                    'valuesSI': values})
            else:
                self.g[index] = rows[0][2]
        if diagnostics:
            raise AdmissionError('', '', '', diagnostics=diagnostics)

    # --- integrator interface -----------------------------------------------------------
    def inicial(self):
        return np.array([g(0.0, None) for g in self.g], dtype=float)

    def rhs(self, t, y):
        return np.array([f(t, y) for f in self.f], dtype=float)

    def firma(self, t, y):
        return None

    def dominio(self, t, y):
        return np.array([f(t, y) for f, _ in self.dominios], dtype=float)

    def describir_dominio(self, k):
        return self.dominios[k][1]


def resolver_explicito(modelo):
    source_model = modelo
    if modelo.get("matematico") is None:
        from core.balances import NoGenerable, generar
        try:
            modelo = generar(modelo)
        except NoGenerable as e:
            raise NoSoportado(f"Balance engine: {e}") from e
    sis = SistemaExplicito(modelo)
    m, est = sis.modelo, sis.modelo["estudio"]
    muestras = int(est["muestras"])
    y0 = sis.inicial()
    for f, que in sis.dominios:
        if f(0.0, y0) < 0:
            raise NoSoportado(f"Initial state outside its domain: {que}")
    tray = integrar(sis, y0, sis.tf, rtol=est["rtol"], atol=sis.atol, max_step=sis.tf / (muestras - 1), metodo=sis.metodo)
    t_fin = tray.t_fin
    ts = [x for x in np.linspace(0.0, sis.tf, muestras) if x <= t_fin * (1 + 1e-12)]
    ts = sorted(set(ts) | {t_fin})
    filas = [tray.y(t) for t in ts]
    series = [serie(f"campo.{c}", c, sis.unidades[c], ["t"], [float(y[k]) for y in filas], propietarioId=f"campo:{c}")
              for k, c in enumerate(sis.campos)]
    for oid, nombre, unidad, f in sis.observables:
        series.append(serie(f"observable.{oid}", nombre, unidad, ["t"], [float(f(t, y)) for t, y in zip(ts, filas)], propietarioId=f"observable:{oid}"))
    verif = []
    for vid, desc, f, esc, tol in sis.verificaciones:
        escala = max(max(abs(float(esc(t, y))) for t, y in zip(ts, filas)), 1e-300)
        verif.append({"id": vid, "valor": max(abs(float(f(t, y))) for t, y in zip(ts, filas)) / escala, "tolerancia": tol, "descripcion": desc})
    eventos = []
    for codigo, t, _a, _d, msg in tray.eventos:
        eventos.append(evento(codigo, "t", t, msg))
    provenance = {}
    if any(source_model.get("motores", {}).get(key) for key in ("materialDerivation", "energyDerivation", "thermodynamicDerivation")):
        from .report import compilation_report
        provenance["compilation"] = compilation_report(source_model)
    return conjunto(m["id"], m["nombre"], "parcial" if tray.detenida else "resuelto",
                    {"motor": "rage.compilador.explicito", "metodo": _NOMBRE_METODO[sis.metodo], "firma": None,
                     "pasos": tray.pasos, "rechazos": tray.rechazos, **provenance,
                     **({"mensaje": tray.detenida.mensaje} if tray.detenida else {})},
                    [eje("t", "Time", "tiempo", sis.unidad_t, ts)], series, eventos, verif, modeloId=m["id"])


def _simbolos(e, acc):
    t = e["tipo"]
    if t == "simbolo":
        acc.add(e["id"])
    for k in ("argumentos",):
        for a in e.get(k, []):
            _simbolos(a, acc)
    for k in ("numerador", "denominador", "base", "exponente", "expresion"):
        if k in e:
            _simbolos(e[k], acc)


def _usa(e, sid):
    acc = set()
    _simbolos(e, acc)
    return sid in acc


def _usa_campos(e, indice):
    acc = set()
    _simbolos(e, acc)
    return bool(acc & set(indice))
