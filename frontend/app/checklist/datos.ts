export function documentoChecklist(): string {
  return [
    '# Checklist del Engine',
    '',
    ...checklistMotor.flatMap(grupo => [
      `## ${grupo.nombre}`,
      '',
      ...grupo.hecho.map(item => `- [x] ${item}`),
      ...grupo.pendiente.map(item => `- [ ] ${item}`),
      ...grupo.aplazado.map((item: string) => `- [ ] *Aplazado:* ${item}`),
      '',
    ]),
  ].join('\n');
}
